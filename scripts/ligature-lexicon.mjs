#!/usr/bin/env node
/**
 * Writes src/canvas/ligature-lexicon.ts: word pieces that hold an "f", taken
 * from the SentencePiece vocabularies of Mozilla's translation models (MPL-2.0,
 * the same files the Translate tool downloads, src/translate/catalog.ts).
 * pdf-ligatures.ts reads it to tell which f-ligature (fi, fl, ff, ft…) a
 * PDF's private-use character stands for.
 *
 *   node scripts/ligature-lexicon.mjs
 *
 * - A piece is kept when it is all letters, at least 4 of them, and holds
 *   an "f". A leading "^" marks a piece that starts a word.
 * - The vocabularies are each language's model into English, so English is
 *   in every one of them.
 * - The output is deterministic: the same vocabularies give the same bytes.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "src/canvas/ligature-lexicon.ts");
const RELEASE = "https://github.com/Joost-8/FineNotes-templates/releases/download/translate-1/";
/** Latin-script languages whose typesetting uses f-ligatures. */
const LANGUAGES = ["nl", "de", "fr", "es", "it", "pt", "pl", "sv", "da", "cs"];

/** The pieces of a SentencePiece model file (field 1 of each `pieces` entry). */
function pieces(bytes) {
  const out = [];
  let i = 0;
  const varint = () => {
    let result = 0;
    let shift = 0;
    for (;;) {
      const c = bytes[i++];
      result += (c & 0x7f) * 2 ** shift;
      shift += 7;
      if (c < 0x80) return result;
    }
  };
  const decoder = new TextDecoder();
  while (i < bytes.length) {
    const key = varint();
    const field = Math.floor(key / 8);
    const wire = key % 8;
    if (wire === 2) {
      const n = varint();
      const sub = bytes.subarray(i, i + n);
      i += n;
      if (field === 1 && sub[0] === 0x0a) out.push(decoder.decode(sub.subarray(2, 2 + sub[1])));
    } else if (wire === 0) varint();
    else if (wire === 5) i += 4;
    else if (wire === 1) i += 8;
    else break;
  }
  return out;
}

/** SentencePiece's word-start mark, U+2581. */
const WORD_START = String.fromCharCode(0x2581);
const CATALOG = readFileSync(resolve(ROOT, "src/translate/catalog.ts"), "utf8");
const kept = new Set();
for (const lang of LANGUAGES) {
  // The file name as the catalogue pins it (versions differ by pair).
  const match = new RegExp(String.raw`"(${lang}-en-[\d.]+\.(?:src)?vocab\.spm)"`).exec(CATALOG);
  if (!match) throw new Error(`${lang}-en: no vocabulary in the catalogue`);
  const name = match[1];
  const answer = await fetch(RELEASE + name);
  if (!answer.ok) throw new Error(`${name}: HTTP ${answer.status}`);
  for (const piece of pieces(new Uint8Array(await answer.arrayBuffer()))) {
    const word = (piece.startsWith(WORD_START) ? `^${piece.slice(1)}` : piece).toLowerCase();
    const core = word.replace(/^\^/, "");
    if (core.length >= 4 && core.includes("f") && /^\p{L}+$/u.test(core)) kept.add(word);
  }
}
const sorted = [...kept].sort();
const out = `/**
 * GENERATED by scripts/ligature-lexicon.mjs from the SentencePiece
 * vocabularies of Mozilla's translation models (MPL-2.0) into English from
 * ${LANGUAGES.join(", ")}. Do not edit by hand.
 *
 * ${sorted.length} word pieces holding an "f", lower case, one space between
 * each; "^" marks a piece that starts a word.
 *
 * PURE: data only.
 */

export const LIGATURE_LEXICON =
  ${JSON.stringify(sorted.join(" "))};
`;
writeFileSync(OUT, out);
execFileSync("npx", ["prettier", "--write", OUT], { stdio: "ignore", shell: true });
console.log(`${sorted.length} pieces → ${OUT}`);
